package bootstrap

import (
	"fmt"
	"strings"

	"go.idp.xyz/idp-cargo/internal/contexts/fin"
	finapi "go.idp.xyz/idp-cargo/internal/contexts/fin/api"
	"go.idp.xyz/idp-cargo/internal/contexts/sea"
	seaapi "go.idp.xyz/idp-cargo/internal/contexts/sea/api"
)

// SettingsCatalogueDocPath is where the catalogue document is committed, from the repository's root.
const SettingsCatalogueDocPath = "docs/settings/catalogue.md"

type docItem struct {
	Key, TitleEN, TitleZH, Default, Explanation string
	Values                                      []docValue
	Scopes                                      []string
	Control                                     bool
}

type docValue struct{ ID, TitleEN, TitleZH, Parameter string }

func finDocItems(c finapi.FinSettingsCatalogue) []docItem {
	var out []docItem
	for _, it := range c.Items {
		d := docItem{Key: it.Key, TitleEN: it.TitleEN, TitleZH: it.TitleZH, Default: it.Default, Explanation: it.Explanation, Scopes: it.ScopeKinds, Control: it.InternalControl}
		for _, v := range it.Values {
			d.Values = append(d.Values, docValue{v.ID, v.TitleEN, v.TitleZH, v.Parameter})
		}
		out = append(out, d)
	}
	return out
}

func seaDocItems(c seaapi.SeaSettingsCatalogue) []docItem {
	var out []docItem
	for _, it := range c.Items {
		d := docItem{Key: it.Key, TitleEN: it.TitleEN, TitleZH: it.TitleZH, Default: it.Default, Explanation: it.Explanation, Scopes: it.ScopeKinds, Control: it.InternalControl}
		for _, v := range it.Values {
			d.Values = append(d.Values, docValue{v.ID, v.TitleEN, v.TitleZH, ""})
		}
		out = append(out, d)
	}
	return out
}

func cell(s string) string { return strings.ReplaceAll(strings.ReplaceAll(s, "|", "\\|"), "\n", " ") }

func writeItems(b *strings.Builder, module string, items []docItem) {
	b.WriteString("| Key | Title | Values, strict to loose (default in bold) | Set at | Internal control |")
	for _, p := range profiles {
		b.WriteString(" " + p.ID + " |")
	}
	b.WriteString(" Explanation |\n|---|---|---|---|---|")
	for range profiles {
		b.WriteString("---|")
	}
	b.WriteString("---|\n")
	for _, it := range items {
		var values []string
		for _, v := range it.Values {
			s := v.ID + " (" + v.TitleEN + " / " + v.TitleZH + ")"
			if v.Parameter != "" {
				s += ", with " + v.Parameter
			}
			if v.ID == it.Default {
				s = "**" + s + "**"
			}
			values = append(values, s)
		}
		control := "no"
		if it.Control {
			control = "yes"
		}
		fmt.Fprintf(b, "| %s | %s / %s | %s | %s | %s |", it.Key, cell(it.TitleEN), cell(it.TitleZH), cell(strings.Join(values, "; ")), strings.Join(it.Scopes, ", "), control)
		for _, p := range profiles {
			v, ok := p.Value(module, it.Key)
			if !ok {
				v = "(not listed)"
			}
			b.WriteString(" " + v + " |")
		}
		fmt.Fprintf(b, " %s |\n", cell(it.Explanation))
	}
}

// SettingsCatalogueDocument writes the catalogue document from the catalogues of FIN and SEA and from the profiles: every
// item, its values from strict to loose, its default, the scopes it is set at, whether it is an internal control, and each
// profile's value. cmd/cargo-settings-doc writes it to SettingsCatalogueDocPath; a test fails when the committed file differs.
func SettingsCatalogueDocument() string {
	finCat, seaCat := fin.SettingsCatalogue(), sea.SettingsCatalogue()
	var b strings.Builder
	b.WriteString("# Settings catalogue\n\n" +
		"Generated by `go run ./cmd/cargo-settings-doc` from the catalogues of FIN and SEA and from the profiles; do not edit it. " +
		"A test fails when this file differs from what the program writes.\n\n" +
		"Each item has values ordered from strict to loose; moving an item to a looser value, or setting a legal entity's value looser than the company's, " +
		"needs a second person's approval. The default is the STANDARD profile's value.\n\n")
	b.WriteString("## Profiles\n\n")
	for _, p := range profiles {
		fmt.Fprintf(&b, "- **%s** (%s / %s): %s\n", p.ID, p.TitleEN, p.TitleZH, p.For)
	}
	b.WriteString("\nThe value each profile gives an item is in the profile's column of the tables below.\n\n")
	fmt.Fprintf(&b, "## FIN\n\nCatalogue version `%s`.\n\n", finCat.Version)
	writeItems(&b, ModuleFIN, finDocItems(finCat))
	if len(finCat.Reference) > 0 {
		b.WriteString("\nReference data, kept in FIN's own records and not changed by the settings commands:\n\n| Key | Title | Governs | Changed by | Needs approval |\n|---|---|---|---|---|\n")
		for _, r := range finCat.Reference {
			approval := "no"
			if r.NeedsApproval {
				approval = "yes"
			}
			fmt.Fprintf(&b, "| %s | %s / %s | %s | %s | %s: %s |\n", r.Key, cell(r.TitleEN), cell(r.TitleZH), cell(r.Governs), cell(r.ChangedBy), approval, cell(r.ApprovalNote))
		}
	}
	fmt.Fprintf(&b, "\n## SEA\n\nCatalogue version `%s`.\n\n", seaCat.Version)
	writeItems(&b, ModuleSEA, seaDocItems(seaCat))
	return b.String()
}
